"""Generate the repaired two-register SMC kernel from the Lean MOV export.

All persistent computation words are complete MOFFS address operands. Each read
label occurs once, in its shared routine. The host entry/observation stubs sit
outside the pure computational boundary. This is a native validation artifact;
its complete layout and ISA refinement still require Lean proofs.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
CELLS = 4096

def generate(folder: Path, architecture: str, instructions):
    wide = architecture == "x64"
    ax, sp, word, directive, stride, width = ("rax", "rsp", "qword", "DQ", 16, 8) if wide else ("eax", "esp", "dword", "DD", 8, 4)
    out = ["; Generated by validation/generate_pure.py from the checked Lean kernel."]
    if not wide:
        out += [".686", ".model flat, C"]
    out += ["option casemap:none", ".data", f"HostStack {directive} 0", ".code",
            "PUBLIC PureNativeEntry, PureRegisters, PureHeap, PureLoopTarget, PureKernelStart, PureBoundary",
            "PureNativeEntry PROC", f"    mov {word} ptr [HostStack], {sp}", "    jmp PureKernelStart", "PureNativeEntry ENDP"]
    fields = {}
    owners = {}
    instruction_count = 0

    def field(name, value="0"):
        assert name not in fields
        fields[name] = value

    def emit(text):
        nonlocal instruction_count
        out.append("    " + text)
        instruction_count += 1

    def reset():
        emit(f"xchg {sp}, {word} ptr [StackTop]")
        emit(f"mov {word} ptr [StackTop], {sp}")

    def invoke(routine):
        reset()
        emit("call NEAR PTR " + routine)

    def read(name):
        invoke("Read_" + name)

    def moffs(label, value):
        assert label not in owners, label
        owners[label] = {"instruction": "MOV_MOFFS", "active": True}
        out.append("    DB " + ("48h, 0A3h" if wide else "0A3h"))
        out.append(f"{label} {directive} {value}")

    def inline_read(label, target):
        emit(f"xchg {ax}, {word} ptr [{label}]")
        emit(f"mov {word} ptr [{label}], {ax}")
        emit(f"xchg {ax}, {word} ptr [{ax}]")
        moffs(label, "OFFSET " + target)

    # These words belong to inactive storage instructions, never to .data.
    for name, value in [("StackTop", f"OFFSET ReturnField+{width}"), ("ReturnField", "0"),
                        ("Candidate", "0"), ("BoundaryValue", "OFFSET PureHeap"),
                        ("ZeroValue", "0"), ("ResumeValue", "0"), ("TerminalValue", "OFFSET PureFault"),
                        ("SMCMask", "0"), ("Scratch", "0"), ("Selected", "0"),
                        ("PureLoopTarget", "OFFSET PureBoundary"), ("OffsetZero", "0"), ("OffsetOne", str(stride))]:
        field(name, value)
    targets = {f"R{r}": f"PureRegisters+{stride*r}" for r in range(13)}
    targets.update({name: name for name in ["Candidate", "BoundaryValue", "ZeroValue", "ResumeValue", "TerminalValue", "SMCMask", "OffsetZero", "OffsetOne"]})
    targets["PointerWord"] = "PointerLabel"
    targets["Pointer"] = "PureHeap"

    # Shared readers: the fourth instruction owns this reader's label word.
    for name, target in targets.items():
        # Padding precedes the called entry; no NOP is executed by the reader.
        # MASM's first three forms occupy 13 bytes (x86) / 17 bytes (x64).
        out += [f"ALIGN {width}", f"    DB {(-19 if wide else -14) % width} DUP (90h)"]
        out.append("Read_" + name + ":")
        label = "PointerLabel" if name == "Pointer" else "Label_" + name
        inline_read(label, target)
        reset()
        emit(f"call {word} ptr [ReturnField]")
    assert "PointerLabel" in owners
    # Both conditional guards first save the caller's return PC before any
    # shared reader can overwrite the common code-backed return slot.
    for sense in ["Base", "Offset"]:
        out += [f"ALIGN {width}", f"    DB {(-19 if wide else -14) % width} DUP (90h)"]
        out.append("Guard_" + sense + ":")
        inline_read("Label_Capture_" + sense, "ReturnField")
        emit(f"mov {word} ptr [ResumeValue], {ax}")
        read("Candidate")
        emit(f"mov {word} ptr [Scratch], {ax}")
        read("BoundaryValue")
        emit(f"sub {word} ptr [Scratch], {ax}")
        read("ZeroValue")
        emit(f"mov {word} ptr [SMCMask], {ax}")
        emit(f"sbb {word} ptr [SMCMask], 0")
        cont, term = ("ResumeValue", "TerminalValue") if sense == "Base" else ("TerminalValue", "ResumeValue")
        read(cont)
        emit(f"mov {word} ptr [Selected], {ax}")
        read(term)
        emit(f"xor {word} ptr [Selected], {ax}")
        read("SMCMask")
        emit(f"and {word} ptr [Selected], {ax}")
        read(cont)
        emit(f"xor {word} ptr [Selected], {ax}")
        reset()
        emit(f"call {word} ptr [Selected]")

    out.append("PureKernelStart:")
    source_blocks = []
    for index, item in enumerate(instructions):
        op, a, b, c = item
        a = int(a)
        out.append(f"Source_{index}:")
        begin = instruction_count
        if op == "imm":
            assert b == "offset", "Kernel address constants need an additional constant reader"
            read("OffsetOne" if int(c) else "OffsetZero")
            emit(f"mov {word} ptr [PureRegisters+{stride*a}], {ax}")
        else:
            base, offset = (int(b), int(c)) if op == "load" else (a, int(b))
            read(f"R{offset}")
            emit(f"mov {word} ptr [Candidate], {ax}")
            invoke("Guard_Offset")
            read(f"R{base}")
            emit(f"mov {word} ptr [PointerLabel], {ax}")
            read(f"R{offset}")
            emit(f"add {word} ptr [PointerLabel], {ax}")
            read("PointerWord")
            emit(f"mov {word} ptr [Candidate], {ax}")
            invoke("Guard_Base")
            if op == "load":
                read("Pointer")
                emit(f"mov {word} ptr [PureRegisters+{stride*a}], {ax}")
            else:
                assert op == "store"
                read(f"R{int(c)}")
                # Enter the very same MOFFS instruction as the load's restore.
                # Its mutable operand is not duplicated at a store call site.
                invoke("PointerLabel-" + ("2" if wide else "1"))
        source_blocks.append({"index": index, "instruction": item, "inline_headers": instruction_count-begin})
    reset()
    emit(f"call {word} ptr [PureLoopTarget]")

    # Observation restores the normal host stack. These stubs are excluded
    # from the computational purity contract, just like the caller setup.
    out += ["PureBoundary:", f"    mov {sp}, {word} ptr [HostStack]", "    xor eax, eax", "    ret",
            "PureFault:", f"    mov {sp}, {word} ptr [HostStack]", "    mov eax, 1", "    ret"]
    for name, value in fields.items():
        assert name not in owners
        out += [f"ALIGN {width}", "    DB " + (("90h,90h,90h,90h,90h,90h,48h,0A3h") if wide else "90h,90h,90h,0A3h"), f"{name} {directive} {value}"]
        owners[name] = {"instruction": "MOV_MOFFS", "active": False}

    def pool(name, count, leading=True):
        if leading:
            out.append(f"ALIGN {stride}")
            out.append(f"    DB {stride-(2 if wide else 1)} DUP (90h)")
        else:
            out.append(f"    DB {stride-width-(2 if wide else 1)} DUP (90h)")
        for index in range(count):
            out.append("    DB " + ("48h,0A3h" if wide else "0A3h"))
            if not index:
                out.append(name + " LABEL BYTE")
            out.append(f"    {directive} 0")
            if index != count-1:
                out.append(f"    DB {stride-width-(2 if wide else 1)} DUP (90h)")
        owners[name] = {"instruction": "MOV_MOFFS", "active": False, "fields": count, "stride": stride}
    pool("PureRegisters", 13)
    pool("PureHeap", 2*CELLS, leading=False)
    # This host-only descriptor table permits checking actual linked template
    # bytes, alignment, and disjointness before entering the computation.
    descriptor_names = [name for name in owners if name not in ["PureRegisters", "PureHeap"]]
    out += [".data", "PUBLIC PureFieldCount, PureFieldAddresses", f"PureFieldCount DD {len(descriptor_names)}",
            "PureFieldAddresses LABEL " + word.upper()]
    out += [f"    {directive} OFFSET {name}" for name in descriptor_names]
    out.append("END")
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "pure.asm").write_text("\n".join(out) + "\n")
    record = {"architecture": architecture, "word_bytes": width, "stride": stride, "heap_cells": CELLS,
              "owners": owners, "source_blocks": source_blocks,
              "boundary": "PureKernelStart and shared routines, excluding host setup/PureBoundary/PureFault"}
    (folder / "layout.json").write_text(json.dumps(record, indent=2) + "\n")
    cpp = ["#pragma once", "struct Operation { int kind, a, b, c; };", "constexpr Operation kernel[] = {"]
    for op, a, b, c in instructions:
        cpp.append("  {" + ",".join([str({"imm":0,"load":1,"store":2}[op]),a, "0" if b=="offset" else b,c]) + "},")
    cpp += ["};", f"constexpr unsigned heapCells = {CELLS};", f"constexpr unsigned stride = {stride};"]
    (folder / "kernel.hpp").write_text("\n".join(cpp) + "\n")
    return record

if __name__ == "__main__":
    kernel = json.loads((ROOT / "validation/kernel.json").read_text())["instructions"]
    for arch in ["x86", "x64"]:
        generate(ROOT / "validation/.build/pure" / arch, arch, kernel)
